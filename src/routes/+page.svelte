<script lang="ts">
  import { onMount } from "svelte";
  import { native, platformInfo, qrSvg, type PlatformInfo } from "#lib/platform.ts";

  let info = $state<PlatformInfo>();
  let text = $state("https://tauri.app");
  let svg = $state("");
  let error = $state("");
  let elapsed = $state(0);

  onMount(async () => {
    info = await platformInfo();
  });

  // Re-render the QR code whenever the text changes
  $effect(() => {
    const value = text;
    if (!value) return void (svg = "");
    const start = performance.now();
    qrSvg(value)
      .then((s) => {
        if (value !== text) return; // a newer request superseded this one
        svg = s;
        error = "";
        elapsed = performance.now() - start;
      })
      .catch((e) => (error = String(e)));
  });
</script>

<main class="mx-auto flex min-h-screen max-w-xl flex-col gap-6 p-6">
  <header class="flex items-center justify-between">
    <h1 class="h3">Tauri + Svelte + Rust</h1>
    <a href="/graphics" class="anchor">Graphics demo →</a>
  </header>

  <section class="card preset-outlined-surface-200-800 space-y-1 p-4">
    <h2 class="h6">Platform</h2>
    {#if info}
      <p>
        Running as <span class="badge preset-filled-primary-500">{info.runtime}</span> on {info.os}
      </p>
      <p class="text-surface-600-400 truncate text-xs" title={info.version}>{info.version}</p>
    {:else}
      <p>Detecting…</p>
    {/if}
  </section>

  <section class="card preset-outlined-surface-200-800 space-y-3 p-4">
    <h2 class="h6">QR code</h2>
    <p class="text-sm">
      Generated by the shared Rust <code class="code">app-core</code> crate via
      {native ? "a native Tauri command" : "WebAssembly"}.
    </p>
    <input class="input" placeholder="Text to encode" bind:value={text} />
    {#if error}
      <p class="text-error-500">{error}</p>
    {:else if svg}
      <!-- SVG comes from our own Rust encoder, not user-controlled markup -->
      <div class="mx-auto w-56 overflow-hidden rounded-lg bg-white [&>svg]:h-auto [&>svg]:w-full">
        {@html svg}
      </div>
      <p class="text-surface-600-400 text-center text-xs">{elapsed.toFixed(1)} ms</p>
    {/if}
  </section>
</main>
